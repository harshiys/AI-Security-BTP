"""SYNTHETIC adapters in an INVENTED layout, used ONLY to exercise the pipeline code.
This is NOT PADBench: its layout, labels and statistics are made up here and prove nothing about real data.

The generator itself decides that its own folder 'label0' holds the synthetic benign adapters and 'label1' the
synthetic backdoored ones. That is a property of THIS FAKE FIXTURE and says NOTHING about what label0/label1
mean in the real PADBench dataset (which is unverified)."""
import json, sys
from pathlib import Path
import numpy as np
sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from c1.safeload import write_safetensors

root = Path(sys.argv[1]); rng = np.random.default_rng(7)
# usage: make_synthetic_root.py ROOT [N_PER_CLASS=14] [RANKS=4,8,16,32,64]
D, LAYERS = 192, 8
N_PER = int(sys.argv[2]) if len(sys.argv) > 2 else 14
RANKS = [int(x) for x in sys.argv[3].split(",")] if len(sys.argv) > 3 else [4, 8, 16, 32, 64]
for rank in RANKS:
    folder = root / f"synthetic_rank{rank}_qv"
    folder.mkdir(parents=True, exist_ok=True)
    # decoy metadata: must never be used as labels (cf. toxicity-probability CSVs next to real adapters)
    (folder / "toxicity_probs_decoy.csv").write_text("adapter,toxicity_prob\nadapter_0000,0.99\n", encoding="utf-8")
    for lab in ("benign", "backdoor"):
        for n in range(N_PER):
            d = folder / ("label0" if lab == "benign" else "label1") / f"adapter_{n:04d}"; d.mkdir(parents=True, exist_ok=True)
            T = {}
            hit = set(rng.choice(LAYERS, size=2, replace=False)) if lab == "backdoor" else set()
            for L in range(LAYERS):
                for mod in ("q_proj", "v_proj"):
                    A = rng.normal(size=(rank, D)) / np.sqrt(D)
                    sv = np.exp(-rng.uniform(0.05, 0.25) * np.arange(rank))
                    B = rng.normal(size=(D, rank)) * sv * 0.05
                    if L in hit:  # backdoor: extra dominant direction, with overlap between classes
                        B[:, 0] *= 1.0 + max(0.0, rng.normal(0.35, 0.45)) * 2.0
                    k = f"base_model.model.model.layers.{L}.self_attn.{mod}"
                    T[f"{k}.lora_A.weight"], T[f"{k}.lora_B.weight"] = A.astype(np.float32), B.astype(np.float32)
            write_safetensors(d / "adapter_model.safetensors", T, bf16=(n % 5 == 0))
            (d / "adapter_config.json").write_text(json.dumps({"r": rank, "lora_alpha": 2 * rank}), encoding="utf-8")
(root / "SYNTHETIC_NOT_PADBENCH.txt").write_text(
    "Fake adapters generated by tests/make_synthetic_root.py for unit/self-testing only.\n"
    "Never use for training or reporting; never mix with real PADBench data.\n", encoding="utf-8")
print("SYNTHETIC (fake) root written:", root)
